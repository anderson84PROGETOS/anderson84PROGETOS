# ===================== FUNÇÕES BÁSICAS =====================
def fetch(url, method="GET", data=None, headers=None, user_agent=USER_AGENT):
    hdrs = {"User-Agent": user_agent, "Accept": "*/*", "Connection": "close"}
    if headers:
        hdrs.update(headers)
    req = urllib.request.Request(url, data=data, method=method, headers=hdrs)
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    try:
        resp = urllib.request.urlopen(req, timeout=TIMEOUT, context=ctx)
        body = resp.read(50000).decode("utf-8", "ignore")
        return resp.status, dict(resp.headers), body
    except urllib.error.HTTPError as e:
        body = e.read(50000).decode("utf-8", "ignore") if e.fp else ""
        return e.code, dict(e.headers or {}), body
    except Exception as e:
        return None, {}, f"ERROR:{e}"

def normalize_headers(h):
    return {k.lower(): str(v).lower() for k, v in h.items()}

def match_fingerprint(status, headers, body):
    hl = normalize_headers(headers)
    bl = body.lower()
    best = (None, 0)
    for fp in WAF_FINGERPRINTS:
        score = 0
        for hk, hv in fp["headers"].items():
            if hk in hl and (not hv or hv in hl[hk]):
                score += 2
        for sig in fp["body"]:
            if sig in bl:
                score += 3
        if fp["status"] and status in fp["status"]:
            score += 1
        if score > best[1]:
            best = (fp["name"], score)
    return best

def detect_generic_block(status, body):
    generic = ["blocked", "forbidden", "denied", "firewall", "security", "protection", "waf", "malicious", "attack detected", "violation"]
    if status in (403, 406, 429, 501):
        bl = body.lower()
        hits = [g for g in generic if g in bl]
        if hits:
            return hits
    return None

def resolve_host(host):
    try:
        return socket.gethostbyname(host)
    except Exception:
        return None

# ===================== PIPELINE =====================
def scan_target(url, log, stop_flag, user_agent=USER_AGENT, ua_label=""):
    buffer = []
    def dual_log(msg):
        buffer.append(msg)
        log(msg)

    result = {"url": url, "waf": "Nenhum detectado", "details": [], "log": [],
              "user_agent": user_agent, "ua_label": ua_label}
    if not url.startswith("http"):
        url = "http://" + url
    p = urlparse(url)
    host, scheme = p.hostname, p.scheme or "http"
    port = p.port or (443 if scheme == "https" else 80)

    dual_log(f"[*] Alvo: {url}")
    dual_log(f"[*] Porta: {port}")
    # Mostra o User-Agent COMPLETO nos resultados
    dual_log(f"[*] User-Agent utilizado: {user_agent}")
    if ua_label:
        dual_log(f"[*] Origem do User-Agent: {ua_label}")
    ip = resolve_host(host)
    dual_log(f"[*] DNS resolvido: {host} -> {ip or 'FALHA'}")
    if not ip:
        result["details"].append("Falha na resolução DNS")
        result["log"] = buffer
        return result

    # Baseline
    try:
        status, headers, body = fetch(url, user_agent=user_agent)
    except Exception as e:
        dual_log(f"[!] Erro na requisição: {e}")
        result["details"].append(f"Erro de conexão: {e}")
        result["log"] = buffer
        return result
    dual_log(f"[*] Baseline: HTTP {status} | Server: {headers.get('Server', 'n/a')}")
    result["details"].append(f"Baseline: HTTP {status}, Server={headers.get('Server','-')}")
    result["details"].append(f"User-Agent: {user_agent}")
    base_headers, base_body = normalize_headers(headers), body.lower()

    waf, score = match_fingerprint(status, headers, body)
    if waf and score >= 3:
        dual_log(f"[+] WAF detectado no baseline: {waf} (score {score})")
        result["waf"] = waf
        result["details"].append(f"Identificado no baseline (score {score})")
        result["log"] = buffer
        return result

    # Malicious tests
    tests = [
        (url + "/?q=<script>alert(1)</script>", None, "XSS via query string"),
        (url + "/?id=1%20OR%201=1", None, "SQLi via query string"),
        (url + "/?file=../../etc/passwd", None, "LFI/path traversal"),
        (url + "/?cmd=;cat%20/etc/passwd", None, "RCE via query string"),
        (url + "/", MALICIOUS_BODY.encode(), "SQLi no corpo (POST)"),
    ]

    for turl, tdata, label in tests:
        if stop_flag.is_set():
            dual_log("[*] Scan interrompido.")
            result["log"] = buffer
            return result
        dual_log(f"\n[*] Testando: {label} -> {turl}\n")
        try:
            s, h, b = fetch(turl, data=tdata, user_agent=user_agent,
                            headers={"Content-Type": "application/x-www-form-urlencoded"} if tdata else None)
        except Exception as e:
            dual_log(f"[!] Falha no teste {label}: {e}")
            continue
        if s is None:
            dual_log(f"[!] Falha: {b}")
            continue

        dual_log(f"    -> HTTP {s} (tamanho resposta: {len(b)})")

        changed = (s != status) or (abs(len(b) - len(body)) > 200) or (normalize_headers(h).get("server") != base_headers.get("server"))
        waf, score = match_fingerprint(s, h, b)
        if waf and score >= 3:
            dual_log(f"[+] WAF identificado: {waf} (score {score})")
            result["waf"] = waf
            result["details"].append(f"Gatilho: {label} -> HTTP {s}")
            result["log"] = buffer
            return result
        if changed and s in (403, 406, 429, 501):
            g = detect_generic_block(s, b)
            if g:
                dual_log(f"[~] Bloqueio genérico detectado ({', '.join(g)}) — WAF desconhecido")
                result["waf"] = "WAF genérico (desconhecido)"
                result["details"].append(f"Bloqueio HTTP {s} no teste '{label}': {', '.join(g)}")
                result["log"] = buffer
                return result
        dual_log("[-] Nenhum bloqueio observado neste teste")

    dual_log("[*] Scan concluído.")
    result["log"] = buffer
    return result

